#!/usr/bin/env python3
"""Deterministic new-SC injector (zero model calls).

Reads a frozen stage-2 run's compiled claim (constraints.json -- the exact
expressions the Z3 queries use) plus a hand-authored binding map, and emits a
runnable new SC:

  new_sc__<case>/
    contract.flattened.t.sol   copied verbatim (sha256 recorded, never edited)
    InvariantGuard.t.sol       generated guard test (P/I/V assertions)
    foundry.toml
    injection-map.json         binding map + translated expressions
    sc-spec.json               the unified stage-2/1/3 interface

The guard test never hard-fails on invariant violation -- a violated I is the
expected outcome on vulnerable code (that IS the finding).  It hard-fails only
on binding impossibilities and reports the P/I/V truth values via one
STAGE2_VERDICT console line plus an event.

Regenerate: /root/.local/share/uv/tools/halmos/bin/python inject.py
"""

import hashlib
import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
STAGE2 = HERE.parents[1]
EVAL = STAGE2 / 'evaluation'
REPO = STAGE2.parents[1]

RUN_GLOB = EVAL / 'prompt_live4_blind_01' / 'runs' / 'Ekubo*'
CASE_KEY = 'Ekubo_3FTodhsvBkM__9MpUh5dZn3f__nFbsAHPP4jP'
CASE_DIR = Path('/root/poc_repro_work/verified_flatten_pass_1568_exact_cases') / CASE_KEY
CLAIM_ID = 'core_claim'
CONTRACT_NAME = 'Stage2InvariantGuard'

BINARY_OPS = {'and': '&&', 'or': '||', 'ne': '!=', 'eq': '==',
              'lt': '<', 'le': '<=', 'gt': '>', 'ge': '>='}

FOUNDARY_TOML = '''[profile.default]
src = "."
test = "."
out = "out"
libs = ["lib"]
via_ir = true
optimizer = true
optimizer_runs = 200
'''


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def translate(node, symbols):
    """op-args/var expression (the compiled Z3 source) -> a Solidity bool."""
    if isinstance(node, bool):
        return 'true' if node else 'false'
    if isinstance(node, int):
        return f'uint256({node})'
    if isinstance(node, dict) and 'var' in node:
        row = symbols[node['var']]
        return f'({row["expr"]})'
    op, args = node['op'], node['args']
    if op == 'not':
        return f'(!{translate(args[0], symbols)})'
    if op == 'implies':
        return f'((!{translate(args[0], symbols)}) || {translate(args[1], symbols)})'
    if op in BINARY_OPS:
        left, right = (translate(a, symbols) for a in args)
        return f'({left} {BINARY_OPS[op]} {right})'
    raise ValueError(f'unsupported expression node: {node!r}')


def guard_sol(binding, expressions, case_key):
    """The generated Solidity guard test (deterministic template fill)."""
    inherits = binding['state'].get('inherits', 'Test')
    state = '\n        '.join(binding['state']['declarations']) or '    '
    setup = '\n        '.join('        ' + line for line in binding['setup'])
    attack = '\n        '.join('        ' + line for line in binding['attack'])
    post = '\n        '.join('        ' + line for line in binding['post'])
    sanity = '\n        '.join('        ' + line for line in binding['binding_sanity'])
    p, i, v = expressions['preconditions'], expressions['safety'], expressions['effects']
    return f'''// SPDX-License-Identifier: MIXED
pragma solidity >=0.8.30;
pragma abicoder v2;

// Generated by evaluation/new_sc_injection_01/inject.py (deterministic, zero
// model calls). Case: {case_key}.  Do not edit -- regenerate instead.
// The P/I/V expressions below are byte-identical to the stage-2 compiled
// claim in constraints.json (the same source the Z3 queries use); only the
// symbol bindings come from bindings/ekubo.json.
import "./contract.flattened.t.sol";

contract {CONTRACT_NAME} is {inherits} {{
    {state}

    event Stage2Verdict(bool pHolds, bool iHolds, bool vHolds);

    // setUp is inherited from the PoC test contract; the scenario setup below
    // belongs to the attack test itself (it declares its own local addresses).
    function testStage2InjectedInvariants() public {{
        // --- scenario setup (the PoC's pre-attack state) ---
{setup}

        // --- attack action (the PoC scenario's T transition) ---
{attack}

        // --- post-state observables ---
{post}

        // --- stage-2 claim, translated against the bindings ---
        // P (preconditions):   {p['source']}
        bool pHolds = {p['solidity']};
        // I (safety):          {i['source']}
        bool iHolds = {i['solidity']};
        // V (effects):         {v['source']}
        bool vHolds = {v['solidity']};

        emit Stage2Verdict(pHolds, iHolds, vHolds);
        console.log("STAGE2_VERDICT", string(abi.encodePacked(
            '{{\\"p\\":', pHolds ? "true" : "false",
            ',\\"i\\":', iHolds ? "true" : "false",
            ',\\"v\\":', vHolds ? "true" : "false", '}}')));

        // The test hard-fails ONLY on binding impossibilities; a violated I
        // is the expected finding on vulnerable code, not a test failure.
{sanity}
    }}
}}
'''


def main():
    runs = sorted(RUN_GLOB.parent.glob(RUN_GLOB.name))
    if len(runs) != 1:
        sys.exit(f'expected exactly one Ekubo run, found {len(runs)}')
    run = runs[0]

    if not CASE_DIR.is_dir():
        sys.exit(f'case dir missing: {CASE_DIR}')
    slice_file = CASE_DIR / 'contract.flattened.t.sol'

    binding = json.loads((HERE / 'bindings' / 'ekubo.json').read_text())
    symbols = binding['symbols']
    bundle = json.loads((run / 'constraints.json').read_text())
    claim = next(row for row in bundle['claims'] if row['id'] == CLAIM_ID)
    plan = json.loads((run / 'formal-plan.json').read_text())

    def compile_expr(kind):
        source = claim['properties'][kind]['expression']
        return {'source': json.dumps(source, ensure_ascii=False),
                'solidity': translate(source, symbols)}

    expressions = {kind: compile_expr(kind)
                   for kind in ('preconditions', 'safety', 'effects')}

    out = HERE / f'new_sc__{CASE_KEY}'
    if out.exists():
        sys.exit(f'refusing to overwrite existing new-SC dir: {out}')
    out.mkdir()

    shutil.copy2(slice_file, out / 'contract.flattened.t.sol')
    (out / 'foundry.toml').write_text(FOUNDARY_TOML)
    (out / 'InvariantGuard.t.sol').write_text(
        guard_sol(binding, expressions, CASE_KEY))

    injection_map = {
        'schema_version': 'stage2-newsc-injection-map/1',
        'case_key': CASE_KEY,
        'claim_id': CLAIM_ID,
        'symbols': {name: {'phase': row['phase'], 'type': row['type'],
                           'expr': row['expr'],
                           'binding_description': row['binding_description']}
                    for name, row in symbols.items()},
        'expressions': {kind: {'source': row['source']}
                        for kind, row in expressions.items()},
        'symbol_sorts': {name: row.get('sort')
                         for name, row in plan['symbols'].items()},
    }
    (out / 'injection-map.json').write_text(
        json.dumps(injection_map, ensure_ascii=False, indent=2) + '\n')

    sc_spec = {
        'schema_version': 'stage2-sc-spec/1',
        'case_key': CASE_KEY,
        'stage2_run': {
            'batch': 'prompt_live4_blind_01',
            'run_dir': str(run.relative_to(REPO)),
            'claim_id': CLAIM_ID,
            'commit_at_injection': '1ec7cb4',
        },
        'slice': {
            'source': str(CASE_DIR),
            'file': 'contract.flattened.t.sol',
            'sha256': sha256(out / 'contract.flattened.t.sol'),
            'poc_status': 'passing (verified_flatten_pass corpus)',
        },
        'claim': {
            'preconditions': claim['properties']['preconditions']['expression'],
            'safety': claim['properties']['safety']['expression'],
            'effects': claim['properties']['effects']['expression'],
            'source_of_truth': 'constraints.json (same expressions the Z3 '
                               'queries use; never re-derived)',
        },
        'symbol_bindings': injection_map['symbols'],
        'code_queries_after_binding': {
            'P_and_T': 'attack executed and bound P holds',
            'P_and_T_and_not_I': 'bound P holds and bound I violated',
            'P_and_T_and_V': 'bound P holds and bound V observed',
            'P_and_T_and_not_V': 'bound P holds and bound V not observed',
        },
        'injected': {
            'guard_file': 'InvariantGuard.t.sol',
            'guard_contract': CONTRACT_NAME,
            'test': f'{CONTRACT_NAME}.testStage2InjectedInvariants',
            'runner': 'forge test --match-contract ' + CONTRACT_NAME,
            'verdict_line': 'STAGE2_VERDICT',
        },
        'model_calls': 0,
    }
    (out / 'sc-spec.json').write_text(
        json.dumps(sc_spec, ensure_ascii=False, indent=2) + '\n')

    print(f'wrote {out}')
    for kind, row in expressions.items():
        print(f'  {kind}: {row["solidity"]}')


if __name__ == '__main__':
    main()
