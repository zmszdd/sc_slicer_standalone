#!/usr/bin/env python3
"""Promote a negative stage2 recovery only when it creates eligible evidence.

The cheap recovery experiment (same frozen prompt with ``--continue-on-review``
for zero-claim negative cases) may produce claims that still end in
``partial_binding``.  This gate makes that experiment reproducible without
letting an unsuccessful run silently mutate the frozen goldset.

Modes:
  evaluate  read-only comparison of baseline and candidate eligibility;
  promote   validate, back up, then replace the candidate stage2 directories;
  restore   put the backed-up stage2 directories back.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
STAGE3 = HERE.parents[1]
if str(STAGE3) not in sys.path:
    sys.path.insert(0, str(STAGE3))
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from lib import claim_population, mainline_protocol  # noqa: E402
from lib import artifact_fingerprint  # noqa: E402
from current_denominator import (  # noqa: E402
    _runs_claims, audit, metric_eligible_cases,
)

SCHEMA_VERSION = 'negative-recovery-gate/1'
REQUIRED_STAGE2 = ('stage3-spec.json', 'constraints.json', 'formalization.json')
SAMPLE = HERE / 'mainline_sample_mini.json'
GOLDSET = HERE / 'mainline_goldset_1_7_31_neg'
RUNS = STAGE3 / 'runs'
BACKUP = HERE.parents[2] / 'c4_pipeline_output' / 'negative_recovery_backup'


def _load(path: Path) -> dict:
    try:
        payload = json.loads(Path(path).read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return {}
    return payload if isinstance(payload, dict) else {}


def _sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _case_dirs(goldset: Path) -> dict[str, Path]:
    found: dict[str, Path] = {}
    for run_dir in sorted(Path(goldset).glob('runs_*')):
        for case_dir in sorted(run_dir.iterdir()):
            if case_dir.is_dir() and (case_dir / 'stage3-spec.json').is_file():
                found.setdefault(case_dir.name, case_dir.resolve())
    return found


def _eligible_by_label(sample_path: Path, runs_dir: Path,
                       population: dict[str, frozenset[str]]) -> dict[str, set[str]]:
    sample = _load(sample_path)
    rows = _runs_claims(sample, Path(runs_dir), population)
    eligible = audit(rows)['sets']['eligible_current']
    cases = metric_eligible_cases(eligible)
    return {
        label: set(case_ids)
        for label, case_ids in cases.items()
        if case_ids
    }


def _validate_candidate(case: str, candidate_dir: Path, negatives: set[str],
                        errors: list[str]) -> dict:
    if case not in negatives:
        errors.append(f'{case}: not a frozen negative sample case')
    for name in REQUIRED_STAGE2:
        if not (candidate_dir / name).is_file():
            errors.append(f'{case}: missing stage2 artifact {name}')
    spec = _load(candidate_dir / 'stage3-spec.json')
    claims = spec.get('claims') or []
    if not claims:
        errors.append(f'{case}: candidate stage2 produced zero claims')
    provenance = _load(candidate_dir / 'provenance.json')
    protocol = mainline_protocol.current()
    checks = {
        'prompt_version': provenance.get('prompt_version'),
        'model_provider': provenance.get('model_provider'),
        'model_name': provenance.get('model_name'),
    }
    expected = {
        'prompt_version': protocol['stage2_prompt_version'],
        'model_provider': protocol['stage2_provider'],
        'model_name': protocol['stage2_model'],
    }
    for key, value in checks.items():
        if value != expected[key]:
            errors.append(f'{case}: {key}={value!r}, expected {expected[key]!r}')
    if not provenance.get('continue_on_review'):
        errors.append(f'{case}: candidate was not generated by the zero-claim fallback')
    return {
        'case': case,
        'claims': len(claims),
        'claim_ids': [str(row.get('claim_id')) for row in claims
                      if isinstance(row, dict) and row.get('claim_id')],
        'stage2_sha256': {name: _sha256(candidate_dir / name)
                          for name in REQUIRED_STAGE2
                          if (candidate_dir / name).is_file()},
        'provenance': checks,
    }


def _candidate_goldset(goldset: Path, existing: dict[str, Path],
                       candidates: dict[str, Path], temp_root: Path) -> Path:
    root = temp_root / 'candidate_goldset'
    run_dir = root / 'runs_01'
    run_dir.mkdir(parents=True)
    for case, path in existing.items():
        target = run_dir / case
        if not target.exists():
            target.symlink_to(path, target_is_directory=True)
    for case, path in candidates.items():
        target = run_dir / case
        if target.exists() or target.is_symlink():
            target.unlink()
        target.symlink_to(path.resolve(), target_is_directory=True)
    return root


def evaluate(sample_path: Path = SAMPLE, goldset_root: Path = GOLDSET,
             runs_dir: Path = RUNS,
             candidate_stage2_root: Path | None = None) -> dict:
    sample = _load(sample_path)
    negatives = {str(case) for case in sample.get('negative_cases') or []}
    positives = {str(case) for case in sample.get('positive_cases') or []}
    existing = _case_dirs(goldset_root)
    errors: list[str] = []
    candidate_dirs: dict[str, Path] = {}
    candidates: list[dict] = []
    if candidate_stage2_root is not None:
        for path in sorted(Path(candidate_stage2_root).iterdir()):
            if path.is_dir() and path.name in negatives:
                candidate_dirs[path.name] = path.resolve()
                candidates.append(_validate_candidate(path.name, path,
                                                      negatives, errors))
    if not candidate_dirs:
        errors.append('no candidate stage2 directories for frozen negative cases')

    original_roots = claim_population.GOLDSET_ROOTS
    try:
        claim_population.GOLDSET_ROOTS = (Path(goldset_root),)
        baseline_population = claim_population.current_claim_ids(sample_path)
    finally:
        claim_population.GOLDSET_ROOTS = original_roots
    baseline = _eligible_by_label(sample_path, runs_dir, baseline_population)
    candidate: dict[str, set[str]] = {}
    with tempfile.TemporaryDirectory(prefix='negative-recovery-') as temp:
        root = _candidate_goldset(goldset_root, existing, candidate_dirs,
                                  Path(temp))
        try:
            claim_population.GOLDSET_ROOTS = (root,)
            candidate_population = claim_population.current_claim_ids(sample_path)
        finally:
            claim_population.GOLDSET_ROOTS = original_roots
        candidate = _eligible_by_label(sample_path, runs_dir,
                                       candidate_population)

    baseline_neg = baseline.get('negative', set())
    candidate_neg = candidate.get('negative', set())
    baseline_pos = baseline.get('positive', set())
    candidate_pos = candidate.get('positive', set())
    new_negative = sorted(candidate_neg - baseline_neg)
    lost_negative = sorted(baseline_neg - candidate_neg)
    lost_positive = sorted(baseline_pos - candidate_pos)
    pass_gate = not errors and bool(new_negative) and not lost_negative \
        and not lost_positive and positives <= baseline_pos
    return {
        'schema_version': SCHEMA_VERSION,
        'protocol': mainline_protocol.current(),
        'sample': str(Path(sample_path).resolve()),
        'candidate_stage2_root': (str(Path(candidate_stage2_root).resolve())
                                  if candidate_stage2_root else None),
        'candidates': candidates,
        'baseline': {
            'eligible_positive': len(baseline_pos),
            'eligible_negative': len(baseline_neg),
        },
        'candidate': {
            'eligible_positive': len(candidate_pos),
            'eligible_negative': len(candidate_neg),
        },
        'new_eligible_negative': new_negative,
        'lost_eligible_negative': lost_negative,
        'lost_eligible_positive': lost_positive,
        'errors': errors,
        'promote_allowed': bool(pass_gate),
    }


def promote(sample_path: Path, goldset_root: Path, runs_dir: Path,
            candidate_stage2_root: Path, backup_root: Path) -> dict:
    report = evaluate(sample_path, goldset_root, runs_dir,
                      candidate_stage2_root)
    if not report['promote_allowed']:
        raise SystemExit('promotion rejected: ' + json.dumps(
            {'errors': report['errors'],
             'new_eligible_negative': report['new_eligible_negative']},
            ensure_ascii=False))
    backup_root.mkdir(parents=True, exist_ok=True)
    existing = _case_dirs(goldset_root)
    for row in report['candidates']:
        case = row['case']
        current = existing[case]
        backup = backup_root / case
        if backup.exists():
            raise SystemExit(f'backup already exists: {backup}')
        shutil.copytree(current, backup)
        candidate = Path(candidate_stage2_root) / case
        shutil.rmtree(current)
        shutil.copytree(candidate, current)
    record = {
        'schema_version': SCHEMA_VERSION,
        'mode': 'promoted',
        'created_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
        'report': report,
    }
    (backup_root / 'promotion.json').write_text(
        json.dumps(record, ensure_ascii=False, indent=2) + '\n',
        encoding='utf-8')
    return record


def restore(goldset_root: Path, backup_root: Path) -> dict:
    if not backup_root.is_dir():
        raise SystemExit(f'backup root not found: {backup_root}')
    existing = _case_dirs(goldset_root)
    restored = []
    for path in sorted(backup_root.iterdir()):
        if not path.is_dir():
            continue
        current = existing.get(path.name)
        if current is None:
            continue
        shutil.rmtree(current)
        shutil.copytree(path, current)
        restored.append(path.name)
    return {'schema_version': SCHEMA_VERSION, 'mode': 'restored',
            'cases': restored}


def markdown(report: dict) -> str:
    lines = [
        '# Negative recovery gate', '',
        f"- protocol: `{report['protocol']['version']}`",
        f"- promote allowed: **{str(report['promote_allowed']).lower()}**", '',
        '| item | baseline | candidate |', '| --- | ---: | ---: |',
        f"| eligible positive | {report['baseline']['eligible_positive']} | "
        f"{report['candidate']['eligible_positive']} |",
        f"| eligible negative | {report['baseline']['eligible_negative']} | "
        f"{report['candidate']['eligible_negative']} |", '',
        '## New eligible negatives', '',
    ]
    lines += [f'- `{case}`' for case in report['new_eligible_negative']] or ['- none']
    lines += ['', '## Errors', '']
    lines += [f'- {error}' for error in report['errors']] or ['- none']
    return '\n'.join(lines) + '\n'


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mode', choices=('evaluate', 'promote', 'restore'),
                        default='evaluate')
    parser.add_argument('--sample', type=Path, default=SAMPLE)
    parser.add_argument('--goldset-root', type=Path, default=GOLDSET)
    parser.add_argument('--runs-dir', type=Path, default=RUNS)
    parser.add_argument('--candidate-stage2-root', type=Path)
    parser.add_argument('--backup-root', type=Path, default=BACKUP)
    parser.add_argument('--out-json', type=Path)
    parser.add_argument('--out-md', type=Path)
    args = parser.parse_args(argv)

    if args.mode == 'restore':
        report = restore(args.goldset_root, args.backup_root)
    elif args.mode == 'promote':
        if args.candidate_stage2_root is None:
            parser.error('--candidate-stage2-root is required for promote')
        report = promote(args.sample, args.goldset_root, args.runs_dir,
                         args.candidate_stage2_root, args.backup_root)
    else:
        report = evaluate(args.sample, args.goldset_root, args.runs_dir,
                          args.candidate_stage2_root)
    if args.out_json:
        args.out_json.parent.mkdir(parents=True, exist_ok=True)
        args.out_json.write_text(json.dumps(report, ensure_ascii=False,
                                            indent=2) + '\n', encoding='utf-8')
    if args.out_md:
        args.out_md.parent.mkdir(parents=True, exist_ok=True)
        args.out_md.write_text(markdown(report), encoding='utf-8')
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
